#!/usr/bin/env python
"""Acceptance test: dbo.uspGetHandlerSourceDetail returns EVERY column of dbo.vwHandlerSourceHistory
except the three it documents as excluded, in the view's own order.

505 is the wide single-record read -- the detail screen behind 503's grid and 504's version list -- and
it is the one read that returns contact names, phone numbers, email addresses and mailing addresses.
Its projection is 215 column names written out longhand. `SELECT *` would be shorter and is refused for
three reasons stated in 505's header, the first being that a projection returning contact details has to
be reviewable by reading the procedure.

THAT CHOICE MOVES THE RISK RATHER THAN REMOVING IT, AND THIS CHECK IS WHERE THE MOVED RISK LANDS.
dbo.HandlerSource and dbo.vwHandlerSourceHistory are GENERATED by build/generate_schema.py from the
RCRAInfo Handler schema. When EPA's spec grows a field, the generator adds a column to the table and to
the view, the deployment applies it, and 505 quietly goes on returning the 215 it knew about. Nothing at
runtime notices: the procedure compiles, the probe passes, the grid works, and the detail screen shows a
record with a field missing that the database has been storing all along. It looks exactly like working
software, which is the same failure mode build/check_cascade_coverage.py exists to catch.

So the list is derived from the catalog and compared, in BOTH directions and including order:

  MISSING     a column the view has that 505 does not return -- the stale-projection failure above.
  EXTRA       a name 505 projects that the view no longer has. The procedure would not compile, so in
              practice this fires when the file has been edited and not deployed, which is worth saying
              plainly rather than discovering at deployment.
  MISORDERED  the same set in a different order. DA5's mapping and any client binding by position care,
              and two columns of the same type transposed is a silent mis-map rather than an error.
  DUPLICATED  a name projected twice -- a copy-paste in a 215-line list, which no compiler rejects.

THREE LISTS ARE COMPARED, NOT TWO. The file's projection, the DEPLOYED procedure's actual first result
set (from sys.dm_exec_describe_first_result_set, which reports the names a caller really receives), and
sys.columns on the view. Checking the file alone would pass on an edit nobody deployed; checking the
deployed module alone would give a failure message with no line to go and fix. Both together also make
file-versus-deployed drift a distinct, named finding.

THE EXCLUSIONS ARE HARD-CODED HERE ON PURPOSE, and adding to them must be a decision rather than a way
to make this check quiet. All three are properties of the VIEW rather than preferences -- IsDeleted is a
constant 0 because the view's own WHERE says so, and the two deletion stamps are masked to NULL unless
the row is deleted, which through this view it cannot be -- so each is provably NULL or constant on every
row 505 can reach. The check also asserts each excluded name still EXISTS in the view: an exclusion for a
column that is gone is a stale exclusion, and the next person to read it would take it as precedent.

If a genuinely new column should be withheld -- and the only current candidate class is PII narrower than
what MDE has already accepted here -- then it is withheld by adding it to EXCLUDED *and* recording the
reason in 505's header, not by adding it to EXCLUDED alone. This check cannot tell those two apart, which
is exactly why the file it is protecting says so out loud.

Requires: sqlcmd on PATH, Windows authentication, and the deployment already applied. Read-only.

Exit 0 when the projection matches the catalog exactly, 1 on a finding, 2 on a setup problem.
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

SCRIPT = Path(__file__).resolve().parents[1] / "src" / "RCRAInfo.Database" / "Scripts" \
    / "505_dbo.uspGetHandlerSourceDetail.sql"

VIEW = "dbo.vwHandlerSourceHistory"
PROCEDURE = "dbo.uspGetHandlerSourceDetail"

# A value the procedure refuses is not usable here: the describe below needs an argument that gets past
# validation, because a procedure that THROWs before its SELECT has no first result set to describe. 1 is
# the lowest id the IDENTITY can ever have issued and the row need not exist -- describe does not run the
# statement, it compiles it.
DESCRIBE_ARGUMENT = 1

# Excluded, and each because of something the VIEW does rather than something anybody preferred. See the
# module docstring before adding to this.
EXCLUDED = {
    "IsDeleted":
        "the view's own WHERE clause is IsDeleted = 0, so through this view it is a constant 0",
    "auditDeletedBy":
        "masked to NULL by the view unless the row is deleted, which through this view it cannot be",
    "auditDeletedDateUtc":
        "the same mask, the same reason",
}

# The view's columns in the order a client receives them from SELECT *, which is the order 505's list has
# to be in. COLLATE DATABASE_DEFAULT because sys.columns.name is sysname and the concatenation below
# otherwise raises a collation conflict on this instance.
CATALOG_QUERY = f"""
SET NOCOUNT ON;
SELECT CAST (c.column_id AS NVARCHAR (11)) + N'|' + c.name COLLATE DATABASE_DEFAULT
  FROM sys.columns AS c
 WHERE c.object_id = OBJECT_ID (N'{VIEW}')
 ORDER BY c.column_id;
"""

# What the DEPLOYED procedure actually hands back. browse_information_mode 0; the third argument to
# describe is not a filter, so every column of the single result set comes back.
DEPLOYED_QUERY = f"""
SET NOCOUNT ON;
SELECT CAST (r.column_ordinal AS NVARCHAR (11)) + N'|' + r.name COLLATE DATABASE_DEFAULT
  FROM sys.dm_exec_describe_first_result_set
       (N'EXEC {PROCEDURE} @HandlerSourceId = {DESCRIBE_ARGUMENT};', NULL, 0) AS r
 ORDER BY r.column_ordinal;
"""


def as_developer(server: str, query: str) -> list[str]:
    exe = shutil.which("sqlcmd")
    if exe is None:
        raise RuntimeError("sqlcmd is not on PATH.")

    # -C trusts the server certificate, which this workstation's default instance needs.
    result = subprocess.run(
        [exe, "-S", server, "-E", "-C", "-b", "-I", "-x", "-d", "RCRAInfo", "-h", "-1", "-W",
         "-Q", query],
        capture_output=True, text=True, encoding="utf-8", errors="replace",
    )

    if result.returncode != 0:
        raise RuntimeError(f"sqlcmd exited {result.returncode}:\n{result.stdout}{result.stderr}")

    return [line.strip() for line in result.stdout.splitlines() if line.strip()]


def ordered_names(rows: list[str], what: str) -> list[str]:
    """Unpack `<ordinal>|<name>` rows, asserting the ordinals are 1..n with no gaps."""
    names: list[str] = []
    for row in rows:
        ordinal, _, name = row.partition("|")
        if not name or not ordinal.isdigit():
            raise RuntimeError(f"unparseable {what} row: {row!r}")
        names.append(name)
    return names


def file_projection(body: str) -> list[str]:
    """505's projected column names, read from the SELECT that feeds off the view.

    Anchored on the FROM clause rather than on the SELECT keyword: `SELECT v.` appears in the CATCH
    block's ERROR_* capture and in the header prose, while `FROM dbo.vwHandlerSourceHistory AS v` in the
    procedure body appears exactly once. Working backwards from it is what makes the match unambiguous.
    """
    marker = f"FROM {VIEW} AS v"
    if body.count(marker) != 1:
        raise RuntimeError(f"expected exactly one `{marker}` in {SCRIPT.name}, "
                           f"found {body.count(marker)}")

    head = body[: body.index(marker)]

    # One column per line, `v.Name`, with the first carrying SELECT and the rest a leading comma. The
    # docstring in 505 says to keep them that way and says why: a comma inside an interleaved comment
    # would otherwise be able to defeat this.
    lines = head.splitlines()
    names: list[str] = []
    for line in reversed(lines):
        stripped = line.strip()
        # The slice ends at the FROM keyword, so the last "line" is the indentation in front of it.
        # Skipped only until the first column is found, so a blank line INSIDE the list still ends the
        # walk rather than being silently stepped over.
        if not stripped and not names:
            continue
        match = re.fullmatch(r"(?:SELECT|,)\s+v\.(\w+)", stripped)
        if match is None:
            break
        names.append(match.group(1))
        if stripped.startswith("SELECT"):
            break

    names.reverse()
    return names


def report(label: str, names: list[str], expected: list[str]) -> int:
    """Compare one list against the catalog's expectation. Returns the number of findings."""
    findings = 0

    duplicated = sorted({n for n in names if names.count(n) > 1})
    if duplicated:
        findings += 1
        print(f"FAIL  {label} projects {len(duplicated)} column(s) more than once: "
              f"{', '.join(duplicated)}")
        print("      No compiler rejects a duplicated column in a 215-name list, and a client binding "
              "by name will read one of the two arbitrarily. Remove the copy.")

    missing = [n for n in expected if n not in names]
    if missing:
        findings += 1
        print(f"FAIL  {len(missing)} column(s) of {VIEW} are NOT returned by {label}:")
        for name in missing:
            print(f"      - {name} (position {expected.index (name) + 1} of {len(expected)})")
        print(f"      This is the stale-projection failure: build/generate_schema.py has added a column "
              f"and the detail screen cannot show it. Add each name to {SCRIPT.name}'s SELECT at its "
              f"catalog position -- after deciding it should be returned. If it should be withheld, add "
              f"it to EXCLUDED here AND say why in {SCRIPT.name}'s header; withholding a column "
              f"silently is how the projection stopped being reviewable in the first place.")

    extra = [n for n in names if n not in expected and n not in EXCLUDED]
    if extra:
        findings += 1
        print(f"FAIL  {len(extra)} name(s) projected by {label} are not columns of {VIEW}: "
              f"{', '.join(extra)}")
        print("      Either the column was renamed or removed by the generator. The procedure would "
              "not compile against the current view, so if this fires on the FILE alone the edit has "
              "not been deployed.")

    wrongly_included = [n for n in names if n in EXCLUDED]
    if wrongly_included:
        findings += 1
        print(f"FAIL  {label} projects {len(wrongly_included)} column(s) documented as excluded:")
        for name in wrongly_included:
            print(f"      - {name}: {EXCLUDED[name]}")
        print("      Each is provably NULL or constant on every row 505 can reach, so returning it "
              "adds a column that means nothing to a 215-column payload -- which is where a real "
              "column goes to hide. Remove it, or remove it from EXCLUDED here and from 505's header "
              "together.")

    if not (missing or extra or duplicated or wrongly_included) and names != expected:
        findings += 1
        first = next(i for i, (a, b) in enumerate(zip(names, expected)) if a != b)
        print(f"FAIL  {label} returns the right {len(names)} columns in the WRONG ORDER. The first "
              f"difference is at position {first + 1}: {VIEW} has {expected[first]!r}, "
              f"{label} has {names[first]!r}.")
        print("      Order is not cosmetic here. DA5's mapping and any client binding by ordinal read "
              "it, and two transposed columns of the same type are a silent mis-map rather than an "
              "error. Restore the catalog's column_id order.")

    return findings


def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--server", default=".", help="target SQL Server instance (default: .)")
    args = parser.parse_args()

    if not SCRIPT.is_file():
        print(f"SETUP  {SCRIPT} not found.")
        return 2

    body = SCRIPT.read_text(encoding="utf-8")

    # Anchored on the FROM clause, not on the star alone: 505's header ARGUES about `SELECT *` in prose
    # and its MS_Description repeats the argument inside a string literal, so neither a comment strip nor
    # a bare search for the token can tell the discussion from the deed. What is banned is a star
    # projection actually reading the view.
    if re.search(r"SELECT\s+(?:TOP\s*\([^)]*\)\s*)?(?:\w+\.)?\*\s+FROM\s+" + re.escape(VIEW),
                 body, re.IGNORECASE):
        print(f"FAIL  {SCRIPT.name} reads {VIEW} with SELECT *. The projection is written out longhand "
              f"deliberately -- see the header. A star projection cannot be reviewed for PII by "
              f"reading the procedure, and it would ship whatever the generator adds next to a web "
              f"page with no decision.")
        return 1

    try:
        catalog = ordered_names(as_developer(args.server, CATALOG_QUERY), "catalog")
        deployed = ordered_names(as_developer(args.server, DEPLOYED_QUERY), "deployed result set")
        in_file = file_projection(body)
    except RuntimeError as exc:
        print(f"SETUP  check_detail_projection could not build its three lists: {exc}")
        return 2

    if not catalog:
        # The view has 218 columns. Zero means the deployment has not run, or the query hit the wrong
        # database -- either way a check that examined nothing must not pass.
        print(f"SETUP  {VIEW} has no columns. Has the deployment run against RCRAInfo on server "
              f"{args.server!r}?")
        return 2

    if not deployed:
        print(f"SETUP  {PROCEDURE} described no result set. Either it is not deployed, or "
              f"@HandlerSourceId = {DESCRIBE_ARGUMENT} no longer gets past its validation -- describe "
              f"cannot see past a THROW.")
        return 2

    if not in_file:
        print(f"SETUP  no projection found in {SCRIPT.name}. The parse walks backwards from "
              f"`FROM {VIEW} AS v` and expects one `, v.Name` per line; an interleaved comment or a "
              f"reflowed list would break it, which is why 505 says to keep the list uniform.")
        return 2

    failures = 0

    stale_exclusions = sorted(name for name in EXCLUDED if name not in catalog)
    if stale_exclusions:
        failures += 1
        print(f"FAIL  {len(stale_exclusions)} documented exclusion(s) are no longer columns of {VIEW}: "
              f"{', '.join(stale_exclusions)}")
        print("      An exclusion for a column that does not exist is a stale exclusion, and the next "
              "person to read it takes it as precedent for excluding something else. Remove it from "
              "EXCLUDED here and from 505's header.")

    expected = [name for name in catalog if name not in EXCLUDED]

    failures += report(f"{SCRIPT.name}'s SELECT", in_file, expected)
    failures += report(f"the DEPLOYED {PROCEDURE}", deployed, expected)

    # Reported separately because the fix is different from every finding above: nothing is wrong with
    # the SQL, the file simply has not been applied. Suppressed when either list already failed against
    # the catalog, or a single added column would report three times.
    if not failures and in_file != deployed:
        failures += 1
        print(f"FAIL  {SCRIPT.name} and the deployed {PROCEDURE} project different column lists, and "
              f"both differ from each other rather than from {VIEW}.")
        print(f"      file {len(in_file)} column(s), deployed {len(deployed)}. Re-run the script: "
              f"sqlcmd -S localhost -E -C -I -d RCRAInfo -y 0 -i {SCRIPT.as_posix()}")

    if failures:
        return 1

    print(f"PASS  detail projection ({len(expected)} of {len(catalog)} {VIEW} column(s) returned by "
          f"{PROCEDURE}, in catalog order, matching in the file and in the deployed module; "
          f"{len(EXCLUDED)} documented exclusion(s) present in the view and absent from the "
          f"projection: {', '.join(sorted(EXCLUDED))})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
