#!/usr/bin/env python
"""Acceptance test: the loader's hand-written lookup catalog still agrees with the pinned EPA spec.

`src/RCRAInfo.Loader/Api/RcraInfoLookup.cs` holds 23 rows typed by hand -- a name, a path segment, and
whether that endpoint takes a `stateCode`. All three were read out of `spec/rcrainfo/swagger.json`, which
is generated by EPA and pinned by build/measure_spec.py. That is the same pairing this project has
already been bitten by twice: a hand-written list over a spec-derived truth (plan [R21]), and the drift
runs one way and runs silently.

Silently, specifically, because of what script 523 does with the answer. A lookup refresh retires every
code it did NOT see, within the activity locations the payload mentions. So a wrong row here does not
produce an error or a missing screen -- it produces a successful run that soft-deletes real codes:

  WRONG PATH SEGMENT   EPA answers 404. No /lookup/hd endpoint documents one, so the client classifies
                       it Unexpected and refreshes nothing -- the mirror silently stops being refreshed,
                       and a list that is never refreshed is indistinguishable from a list EPA has
                       stopped publishing.
  WRONG NAME           523 dispatches its MERGE on the name. A name that is spelled correctly but
                       paired with another list's path refreshes the WRONG table from the right payload:
                       every code in it retired, and the other list never refreshed at all.
  MISSING stateCode    Five endpoints require one and none of them documents a 400, so omitting it is
                       not a clean refusal. It is an undocumented status, or a 200 carrying every
                       jurisdiction's codes -- which 523 then treats as authoritative for all of them.
  SPURIOUS stateCode   Sixteen endpoints have no such parameter. EPA ignores what it does not know, so
                       the request succeeds and the national answer is accepted as a Maryland one.

A fifth silent drift is not in the catalog at all but in the shape the payloads are read into.
`RCRAInfo.Data/Payloads/LookupElement.cs` is one CLR type standing for all 23 response definitions, and
`System.Text.Json` ignores an unmapped member without a word. So a property EPA adds is not a parse
error and not a missing code -- every code still arrives, the refresh still succeeds, and whatever the
new field says about those codes is discarded on every run from then on. The comparison below is by
NAME only, case-insensitively, because that is the only silent direction: a property whose TYPE changes
is refused out loud by LookupPayload.Read, which is what its JsonException path is for.

Seven things are derived from the spec and compared against the file:

  SEGMENT      every catalog path segment is a real GET under /api/v1/lookup/hd/.
  NAME         the definition each endpoint's 200 response returns is named exactly as the catalog names
               it -- which is also script 523's @LookupName.
  COVERAGE     every /lookup/hd GET is either in the catalog or is the one deliberate exclusion, and
               that exclusion still has the property it was excluded for.
  STATECODE    stateCode's presence and its `required` flag agree with LookupStateCode, in both
               directions.
  PARAMETERS   no mirrored endpoint has a REQUIRED parameter the loader does not send, and any optional
               parameter it deliberately ignores is named below rather than passed over.
  STATUSES     RcraInfoDataRequest.DocumentedStatuses matches the spec's response sets, for all four
               endpoint families. That dictionary is what decides whether a 404 soft-deletes data, and
               checking only the lookup row of it would be arbitrary.
  PROPERTIES   the union of the 23 mirrored definitions' property names equals LookupElement's, in both
               directions, and every nested $ref points at a definition that is itself mirrored -- so
               the nested shapes' properties fall inside the union rather than outside the comparison.

The catalog names are also compared against script 523's own dispatch, because the two are the same
closed set written twice and neither file mentions the other. That half needs no server:
build/check_lookup_coverage.py checks 523 against sys.columns and does need one.

Exit 0 when the catalog matches the spec, 1 on a finding, 2 on a setup problem.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SPEC = REPO / "spec" / "rcrainfo" / "swagger.json"
CATALOG = REPO / "src" / "RCRAInfo.Loader" / "Api" / "RcraInfoLookup.cs"
REQUEST = REPO / "src" / "RCRAInfo.Loader" / "Api" / "RcraInfoDataRequest.cs"
REFRESH = REPO / "src" / "RCRAInfo.Database" / "Scripts" / "523_dbo.uspRefreshLookupSet.sql"
ELEMENT = REPO / "src" / "RCRAInfo.Data" / "Payloads" / "LookupElement.cs"

LOOKUP_PREFIX = "/api/v1/lookup/hd/"

# The one query parameter the loader sends to a lookup endpoint. Everything else the spec declares must
# be optional, and must be listed in IGNORED_PARAMETERS with a reason.
SENT_PARAMETER = "stateCode"

# Optional parameters this application knowingly does not send, and what omitting each one means. An
# optional parameter that is not here is a FINDING rather than a shrug: every one of these is a FILTER,
# and a filter the loader does not know about is a filter whose default EPA chooses. If that default
# ever narrows a list, 523 retires everything outside it and reports success.
IGNORED_PARAMETERS = {
    "federal": "Sending federal=true would return only the federal codes of that list, and 523 would "
               "then retire every state-specific code in it. Omitted, so EPA applies no filter and the "
               "payload is the whole list. generator-categories and waste-codes only.",
}

# The endpoint deliberately not mirrored, and the property that justifies it. `term` being REQUIRED is
# what makes /lookup/hd/naics-codes a search rather than a list: there is no set of terms that provably
# covers every code, so an enumeration would look complete and 523 would retire whatever it missed.
# If EPA ever makes `term` optional, this exclusion needs a fresh decision -- so the check fails then.
EXCLUDED_SEGMENT = "naics-codes"
EXCLUDED_BECAUSE_REQUIRED = "term"

# Which spec path serves each RcraInfoDataEndpoint member, for the DocumentedStatuses comparison. The
# lookup family is handled separately: all 24 of its paths must document one identical set, which is
# what lets a single enum member stand for 23 lists.
DATA_ENDPOINT_PATHS = {
    "Summaries": "/api/v1/hd/sources/summaries",
    "Source": "/api/v1/hd/sources/{handlerId}/{sourceType}/{sequence}",
    "OtherIds": "/api/v1/hd/other-ids",
}

CATALOG_ROW = re.compile(
    r"""new\s*\(\s*"(?P<name>\w+)"\s*,\s*"(?P<segment>[\w-]+)"\s*,\s*"""
    r"""LookupStateCode\.(?P<state>\w+)\s*\)""")

STATUS_ROW = re.compile(
    r"""\[RcraInfoDataEndpoint\.(?P<endpoint>\w+)\]\s*=\s*new\[\]\s*\{(?P<statuses>[\d,\s]+)\}""")

PATH_PREFIX_CONST = re.compile(r"""PathPrefix\s*=\s*"(?P<prefix>[^"]+)\"""")
EXCLUDED_CONST = re.compile(r"""ExcludedPathSegment\s*=\s*"(?P<segment>[^"]+)\"""")

# LookupElement's properties. `get; init;` is what every one of them is, and matching on that rather
# than on `public` alone keeps a future method or constant out of the comparison.
CLR_PROPERTY = re.compile(r"""public\s+\S+\s+(?P<name>\w+)\s*\{\s*get;\s*init;\s*\}""")


def spec_lookups(document: dict) -> dict[str, dict]:
    """Every GET under /api/v1/lookup/hd/, keyed by path segment."""
    found: dict[str, dict] = {}
    for path, methods in document["paths"].items():
        if not path.startswith(LOOKUP_PREFIX):
            continue
        get = methods.get("get")
        if get is None:
            continue

        schema = get.get("responses", {}).get("200", {}).get("schema", {})
        if schema.get("type") == "array":
            schema = schema.get("items", {})

        found[path[len(LOOKUP_PREFIX):]] = {
            "definition": schema.get("$ref", "").rsplit("/", 1)[-1] or None,
            "parameters": {
                parameter["name"]: bool(parameter.get("required"))
                for parameter in get.get("parameters", [])
                if parameter.get("name")
            },
            "statuses": {int(status) for status in get.get("responses", {})
                         if status.isdigit()},
        }
    return found


def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, OSError):
        pass

    argparse.ArgumentParser(description=__doc__,
                            formatter_class=argparse.RawDescriptionHelpFormatter).parse_args()

    for required in (SPEC, CATALOG, REQUEST, REFRESH, ELEMENT):
        if not required.is_file():
            print(f"SETUP  {required.relative_to(REPO)} not found.")
            return 2

    document = json.loads(SPEC.read_text(encoding="utf-8"))
    catalog_source = CATALOG.read_text(encoding="utf-8")
    request_source = REQUEST.read_text(encoding="utf-8")
    refresh_source = REFRESH.read_text(encoding="utf-8")
    element_source = ELEMENT.read_text(encoding="utf-8")

    endpoints = spec_lookups(document)
    if not endpoints:
        # 24 in the pinned spec. Zero means the walk stopped matching, and a check that examined
        # nothing must not pass.
        print(f"SETUP  no GET under {LOOKUP_PREFIX} in {SPEC.relative_to(REPO)}. Either the spec moved "
              f"or this check's prefix is stale; build/measure_spec.py --lookups lists what is there.")
        return 2

    rows = [(m.group("name"), m.group("segment"), m.group("state"))
            for m in CATALOG_ROW.finditer(catalog_source)]
    if not rows:
        print(f"SETUP  no catalog rows matched in {CATALOG.relative_to(REPO)}. The row shape this "
              f"check reads is `new(\"Name\", \"path-segment\", LookupStateCode.X)`; if the record's "
              f"construction changed, this pattern has to change with it.")
        return 2

    prefix_match = PATH_PREFIX_CONST.search(catalog_source)
    if prefix_match is None:
        print(f"SETUP  could not find the PathPrefix constant in {CATALOG.relative_to(REPO)}.")
        return 2

    failures = 0

    # ---- The shared prefix ---------------------------------------------------------------------------
    prefix = prefix_match.group("prefix")
    if "/" + prefix != LOOKUP_PREFIX:
        failures += 1
        print(f"FAIL  RcraInfoLookup.PathPrefix is {prefix!r}, but the spec serves these lists under "
              f"{LOOKUP_PREFIX!r}.")
        print("      Every one of the 23 paths is built from this constant, so a stale prefix moves all "
              "of them at once -- to a path EPA does not route, which answers 404, which no lookup "
              "endpoint documents, so every refresh classifies as Unexpected and the whole mirror "
              "quietly stops being refreshed.")

    # ---- SEGMENT and NAME ---------------------------------------------------------------------------
    for name, segment, state in rows:
        endpoint = endpoints.get(segment)
        if endpoint is None:
            failures += 1
            print(f"FAIL  the catalog maps {name} to {prefix}{segment}, which the pinned spec does not "
                  f"serve.")
            print(f"      EPA answers 404 and no /lookup/hd endpoint documents one, so this list is "
                  f"never refreshed and never retired -- and 'never refreshed' looks exactly like "
                  f"'EPA publishes no codes for it'. Known segments: "
                  f"{', '.join(sorted(endpoints))}.")
            continue

        if endpoint["definition"] != name:
            failures += 1
            print(f"FAIL  {prefix}{segment} returns the {endpoint['definition']} definition, but the "
                  f"catalog calls it {name}.")
            print(f"      The name IS script 523's @LookupName and 523 dispatches its MERGE on it, so "
                  f"this pairing refreshes dbo.Lookup{name} from {endpoint['definition']} data: every "
                  f"code in the wrong table retired, and {endpoint['definition']} never refreshed. A "
                  f"misspelling would have been refused by 523; this would not.")

    # ---- COVERAGE -----------------------------------------------------------------------------------
    catalogued = {segment for _, segment, _ in rows}
    excluded_match = EXCLUDED_CONST.search(catalog_source)
    excluded = excluded_match.group("segment") if excluded_match else None

    if excluded != EXCLUDED_SEGMENT:
        failures += 1
        print(f"FAIL  RcraInfoLookups.ExcludedPathSegment is {excluded!r}; this check knows the "
              f"exclusion as {EXCLUDED_SEGMENT!r}. A second deliberate omission needs a decision "
              f"recorded in both places, not a constant that quietly changed meaning.")

    unmirrored = sorted(set(endpoints) - catalogued - {EXCLUDED_SEGMENT})
    if unmirrored:
        failures += len(unmirrored)
        print(f"FAIL  {len(unmirrored)} /lookup/hd endpoint(s) are neither in the catalog nor the "
              f"recorded exclusion: {', '.join(unmirrored)}")
        print("      G15 mirrors the code lists, so a new one is a table to generate, a branch to add "
              "to 523, and a row here -- or an exclusion argued for in IGNORED/EXCLUDED above. Left "
              "alone it is simply a list this application never learns about.")

    if EXCLUDED_SEGMENT in catalogued:
        failures += 1
        print(f"FAIL  {EXCLUDED_SEGMENT} is in the catalog, and it is the one endpoint that must not be. "
              f"It takes a required `{EXCLUDED_BECAUSE_REQUIRED}` and is a SEARCH over the same "
              f"definition as its parameterless sibling. No set of search terms provably covers every "
              f"code, so mirroring it yields a subset that looks complete -- and then 523 retires "
              f"every code the terms happened to miss.")
    else:
        excluded_endpoint = endpoints.get(EXCLUDED_SEGMENT)
        if excluded_endpoint is None:
            failures += 1
            print(f"FAIL  the catalog records {EXCLUDED_SEGMENT} as deliberately excluded, but the spec "
                  f"no longer serves it. An exclusion that names nothing is a comment; either drop it "
                  f"or find what replaced the endpoint.")
        elif not excluded_endpoint["parameters"].get(EXCLUDED_BECAUSE_REQUIRED):
            failures += 1
            print(f"FAIL  {EXCLUDED_SEGMENT} is excluded because `{EXCLUDED_BECAUSE_REQUIRED}` is "
                  f"REQUIRED, which makes it a search rather than a list. The spec no longer says so, "
                  f"so the reason for the exclusion has expired and the decision needs to be taken "
                  f"again -- it may now be mirrorable, and it may now duplicate "
                  f"{excluded_endpoint['definition']}.")

    # ---- STATECODE and PARAMETERS -------------------------------------------------------------------
    for name, segment, state in rows:
        endpoint = endpoints.get(segment)
        if endpoint is None:
            continue  # already reported

        parameters = endpoint["parameters"]
        expected = ("Required" if parameters.get(SENT_PARAMETER)
                    else "Optional" if SENT_PARAMETER in parameters
                    else "Unsupported")

        if state != expected:
            failures += 1
            print(f"FAIL  the catalog declares {name} as LookupStateCode.{state}, but "
                  f"{prefix}{segment} says {expected}.")
            if expected == "Unsupported":
                print(f"      There is no {SENT_PARAMETER} on that endpoint. EPA ignores a parameter it "
                      f"does not know, so the request SUCCEEDS and returns every jurisdiction -- and "
                      f"523 accepts a national payload as though it had been asked for one state.")
            elif state == "Unsupported":
                print(f"      The loader would send no {SENT_PARAMETER} at all. On a {expected.lower()} "
                      f"parameter that means a national payload where a scoped one was intended; where "
                      f"it is required there is no 400 to tell anyone, because these endpoints document "
                      f"none.")
            else:
                print(f"      Required and optional differ only in what happens when the value is "
                      f"missing, and this loader always sends one -- but the enum is also what "
                      f"RcraInfoDataRequest.Lookup refuses on, and its message names which.")

        unknown_required = sorted(
            p for p, required in parameters.items() if required and p != SENT_PARAMETER)
        if unknown_required:
            failures += len(unknown_required)
            print(f"FAIL  {prefix}{segment} requires {len(unknown_required)} parameter(s) the loader "
                  f"never sends: {', '.join(unknown_required)}")
            print("      RcraInfoDataRequest.Lookup composes a stateCode and nothing else, and no "
                  "/lookup/hd endpoint documents a 400 -- so a missing required parameter comes back "
                  "as an undocumented status, or as a 200 carrying more than was asked for.")

        unknown_optional = sorted(
            p for p, required in parameters.items()
            if not required and p != SENT_PARAMETER and p not in IGNORED_PARAMETERS)
        if unknown_optional:
            failures += len(unknown_optional)
            print(f"FAIL  {prefix}{segment} accepts {len(unknown_optional)} optional parameter(s) this "
                  f"check has no decision recorded for: {', '.join(unknown_optional)}")
            print("      Every optional parameter on these endpoints so far is a FILTER, and a filter "
                  "the loader does not send is a filter whose default EPA chooses. If that default "
                  "narrows the list, 523 retires everything outside it and the run reports success. "
                  "Read what it does, then either send it or add it to IGNORED_PARAMETERS with the "
                  "reason omitting it is safe.")

    # ---- STATUSES -----------------------------------------------------------------------------------
    declared = {m.group("endpoint"): {int(s) for s in m.group("statuses").replace(" ", "").split(",")
                                      if s}
                for m in STATUS_ROW.finditer(request_source)}

    if not declared:
        print(f"SETUP  could not read DocumentedStatuses out of {REQUEST.relative_to(REPO)}.")
        return 2

    lookup_sets = {frozenset(e["statuses"]) for e in endpoints.values()}
    if len(lookup_sets) != 1:
        failures += 1
        print(f"FAIL  the {len(endpoints)} /lookup/hd endpoints no longer document ONE identical status "
              f"set; the spec now has {len(lookup_sets)} of them.")
        print("      RcraInfoDataEndpoint.Lookup is a single member standing for all of them, and it is "
              "what decides whether a 404 becomes a soft delete. Distinct sets need distinct members.")
        for statuses in sorted(lookup_sets, key=sorted):
            segments = sorted(s for s, e in endpoints.items() if e["statuses"] == set(statuses))
            print(f"      - {sorted(statuses)}: {', '.join(segments)}")
    else:
        for endpoint_name, statuses in sorted(declared.items()):
            if endpoint_name == "Lookup":
                actual = set(next(iter(lookup_sets)))
                where = f"all {len(endpoints)} /lookup/hd endpoints"
            else:
                path = DATA_ENDPOINT_PATHS.get(endpoint_name)
                if path is None:
                    failures += 1
                    print(f"FAIL  DocumentedStatuses names RcraInfoDataEndpoint.{endpoint_name}, which "
                          f"this check cannot locate in the spec. Add its path to "
                          f"DATA_ENDPOINT_PATHS, or the new endpoint's status set is unchecked -- and "
                          f"that set is what decides whether its 404 deletes data.")
                    continue
                get = document["paths"].get(path, {}).get("get")
                if get is None:
                    failures += 1
                    print(f"FAIL  the spec no longer serves GET {path}, which "
                          f"RcraInfoDataEndpoint.{endpoint_name} reads.")
                    continue
                actual = {int(s) for s in get.get("responses", {}) if s.isdigit()}
                where = f"GET {path}"

            if statuses != actual:
                failures += 1
                print(f"FAIL  RcraInfoDataEndpoint.{endpoint_name} declares "
                      f"{sorted(statuses)}, but {where} documents {sorted(actual)}.")
                if (404 in statuses) != (404 in actual):
                    print("      404 is the difference, and it is the one that matters: "
                          "DocumentsNotFound is what turns a 404 into ApiFetchOutcome.NotFound and "
                          "feeds dbo.uspSoftDeleteHandlerSourceSet. Wrong in one direction it deletes "
                          "records over a mistyped URL; wrong in the other it keeps withdrawn records "
                          "live forever.")
                else:
                    print("      A status outside its endpoint's set classifies as Unexpected, which "
                          "is logged and retried rather than read as data. Both directions of this "
                          "drift are wrong quietly.")

    # ---- PROPERTIES ---------------------------------------------------------------------------------
    definitions = document.get("definitions", {})

    # Keyed by the spec's own spelling, valued by which mirrored lists declare it -- the list names are
    # what makes a finding actionable, because a property on one definition is a different conversation
    # from one on twenty.
    spec_properties: dict[str, set[str]] = {}

    # Every $ref reachable from a mirrored definition's property, direct or through an array's items.
    nested_refs: dict[str, str] = {}

    for name, segment, _ in rows:
        endpoint = endpoints.get(segment)
        if endpoint is None:
            continue  # already reported

        declared = definitions.get(endpoint["definition"], {}).get("properties", {})
        if not declared:
            failures += 1
            print(f"FAIL  the {endpoint['definition']} definition declares no properties in the pinned "
                  f"spec, so {name} contributes nothing to this comparison.")
            print("      Either the definition moved and this check is reading an empty dict as agreement, "
                  "or EPA now returns an untyped body -- and an untyped body read into LookupElement binds "
                  "every property to null while the refresh reports success.")
            continue

        for property_name, shape in declared.items():
            spec_properties.setdefault(property_name, set()).add(name)

            ref = shape.get("$ref") or shape.get("items", {}).get("$ref", "")
            if ref:
                nested_refs[property_name] = ref.rsplit("/", 1)[-1]

    clr_properties = {m.group("name") for m in CLR_PROPERTY.finditer(element_source)}
    if not clr_properties:
        print(f"SETUP  no `get; init;` properties matched in {ELEMENT.relative_to(REPO)}. That is the "
              f"shape this check reads; if the type changed to a record or to settable properties, this "
              f"pattern has to change with it -- an empty set would otherwise agree with anything.")
        return 2

    # Compared case-insensitively because that is how the binding actually behaves: LookupPayload reads
    # with PropertyNameCaseInsensitive, deliberately, so that a national code list does not arrive as a
    # column of nulls over one capital letter. Comparing exactly here would report a disagreement the
    # reader does not have.
    clr_by_lower = {property_name.lower(): property_name for property_name in clr_properties}
    spec_by_lower = {property_name.lower(): property_name for property_name in spec_properties}

    for lowered, property_name in sorted(spec_by_lower.items()):
        if lowered in clr_by_lower:
            continue

        failures += 1
        declaring = sorted(spec_properties[property_name])
        print(f"FAIL  the spec declares `{property_name}` on {len(declaring)} mirrored definition(s) "
              f"({', '.join(declaring)}), and LookupElement has no property for it.")
        print("      System.Text.Json ignores an unmapped member silently, which for a code list is the "
              "quiet kind of wrong: every code still arrives, the refresh still succeeds, and whatever "
              "this field says about those codes is discarded on every run from now on. Add it to "
              "LookupElement, to 523's shred, and to the generated table -- LookupPayload reports the "
              "same thing at runtime, but only once the live service has already moved on.")

    for lowered, property_name in sorted(clr_by_lower.items()):
        if lowered in spec_by_lower:
            continue

        failures += 1
        print(f"FAIL  LookupElement.{property_name} matches no property on any of the {len(rows)} "
              f"mirrored definitions in the pinned spec.")
        print("      Nothing binds it, so its column is NULL on every element of every list -- which "
              "reads as 'EPA publishes no value here' rather than 'nothing ever fills this'. If a spec "
              "property above is also unmatched, the two findings are one rename and fixing either one "
              "alone loses the data.")

    mirrored_definitions = {endpoints[segment]["definition"]
                           for _, segment, _ in rows if segment in endpoints}

    for property_name, target in sorted(nested_refs.items()):
        if target in mirrored_definitions:
            continue

        failures += 1
        print(f"FAIL  `{property_name}` nests the {target} definition, which no mirrored list returns.")
        print("      LookupElement is its own nested type, so a nested shape's properties are covered by "
              "the comparison above only because County and EpisodicType happen to be mirrored lists in "
              "their own right. A nested definition outside the 23 puts its properties outside the union "
              "-- discarded silently by the reader, and invisible to this check as well.")

    # ---- The other half of the closed set: script 523 ------------------------------------------------
    width_clause = re.search(r"@CodeWidth\s*=\s*CASE\s+@LookupName(.*?)\bEND\b",
                             refresh_source, re.DOTALL)
    if width_clause is None:
        print(f"SETUP  could not find the @CodeWidth dispatch in {REFRESH.name}; it is where 523 lists "
              f"the names it accepts.")
        return 2

    dispatch = set(re.findall(r"WHEN\s+N'(\w+)'\s+THEN\s+\d+", width_clause.group(1)))
    names = {name for name, _, _ in rows}

    for missing in sorted(names - dispatch):
        failures += 1
        print(f"FAIL  the catalog fetches {missing}, but {REFRESH.name} does not accept that "
              f"@LookupName. The fetch would succeed and the refresh would throw on every run -- for "
              f"one list, in a load whose other 22 lists work.")

    for orphan in sorted(dispatch - names):
        failures += 1
        print(f"FAIL  {REFRESH.name} can refresh {orphan}, but nothing in the catalog ever fetches it. "
              f"That table stays at whatever it was last loaded with: never refreshed, never retired, "
              f"and reading as a code list EPA has stopped publishing.")

    if failures:
        return 1

    scoped = sum(1 for _, _, state in rows if state != "Unsupported")
    required = sum(1 for _, _, state in rows if state == "Required")
    print(f"PASS  lookup catalog ({len(rows)} mirrored list(s) against {len(endpoints)} spec "
          f"endpoint(s), every segment, definition name and stateCode agreeing; {scoped} take a "
          f"stateCode of which {required} require it; {EXCLUDED_SEGMENT} excluded and still requiring "
          f"`{EXCLUDED_BECAUSE_REQUIRED}`; {len(IGNORED_PARAMETERS)} optional parameter(s) knowingly "
          f"unsent; {len(declared)} documented status set(s) matching the spec; "
          f"{len(spec_by_lower)} property name(s) with a home on LookupElement and no property there "
          f"without one, {len(nested_refs)} nested shape(s) inside the mirrored set; all {len(names)} "
          f"names dispatched by {REFRESH.name})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
