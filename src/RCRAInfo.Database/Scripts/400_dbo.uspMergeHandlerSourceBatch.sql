        -- gets its unchanged count without this procedure parsing the payload a third time.
        SELECT m.HandlerSourceId
             , m.HandlerId
             , m.SourceType
             , m.Sequence
             , CASE m.Action WHEN N'INSERT' THEN N'Inserted' ELSE N'Updated' END AS Outcome
          FROM @Merged AS m
         ORDER BY m.HandlerId, m.SourceType, m.Sequence;

    END TRY
    BEGIN CATCH

        -- The ERROR_* functions are valid only in this scope and any statement can reset them, so
        -- capture them before doing anything else -- including before the rollback.
        SELECT @ErrorNumber = ERROR_NUMBER ()
             , @ErrorProc   = ERROR_PROCEDURE ()
             , @ErrorLine   = ERROR_LINE ()
             , @ErrorMsg    = ERROR_MESSAGE ()
                            + N' (error '  + CAST (ERROR_NUMBER () AS NVARCHAR (11))
                            + N', line '   + CAST (ERROR_LINE ()   AS NVARCHAR (11)) + N')';

        -- One test, not two: XACT_ABORT ON makes XACT_STATE () = -1 the common case, and -1 and 1
        -- both need the same unqualified rollback.
        IF XACT_STATE () <> 0
        BEGIN
            ROLLBACK TRANSACTION;
        END;

        -- The rollback destroyed the row logs.uspStartExecutionLogging wrote. Put it back, with the
        -- ORIGINAL @StartTimeUtc, or the only unrecorded executions in the database would be the
        -- failures. The nested TRY is required because the start procedure does not swallow: an
        -- error escaping here would replace the error being reported.
        BEGIN TRY
            IF @ExecutionId IS NULL
               OR NOT EXISTS (SELECT 1
                                FROM logs.ExecutionLog
                               WHERE ExecutionLogId = @ExecutionId)
            BEGIN
                EXEC logs.uspStartExecutionLogging
                      @ProcedureName          = @ProcName
                    , @KeyParameters          = @KeyParameters
                    , @StartDateUtc           = @StartTimeUtc
                    , @ReCreatedAfterRollback = 1
                    , @ExecutionLogId         = @ExecutionId OUTPUT;
            END;
        END TRY
        BEGIN CATCH
            SET @ExecutionId = NULL;
        END CATCH;

        -----------------------------------------------------------------------------------------
        -- G35, ANSWERED HERE. The AR5 per-handler rows the rollback took away are written back
        -- from @Key, which still holds every element's natural key because a table variable is
        -- not transactional. That property is normally a footgun and is exactly the one required.
        --
        -- No new accumulator was needed: @Key already is one, and it is populated BEFORE
        -- BEGIN TRANSACTION. That is what makes this cover a VALIDATION failure too -- a batch
        -- rejected for a duplicate key never opened a transaction, and its handlers are still
        -- told they failed rather than left at 'Pending' for a monitoring grid to misread as
        -- work still in flight.
        --
        -- What is written, and what is deliberately NOT:
        --   Status          -> 'Failed'. Terminal here: the next attempt is the loader's next
        --                      call, which will set this row itself.
        --   Outcome         -> NULL. The rollback means NOTHING was applied, so stamping the
        --                      outcome the MERGE was going to produce would record work that
        --                      does not exist. @Merged is the tempting source and it is the
        --                      wrong one: those rows describe a transaction that un-happened.
        --   HandlerSourceId -> left alone. The rollback removed nothing that predated this call,
        --                      so whatever is in that column is still true.
        --   ExecutionLogId  -> @ExecutionId, which is the ONLY route from a Failed row to why it
        --                      failed: this table has no column for our own error text and
        --                      ApiErrorMessage must not be borrowed for one, being EPA's and
        --                      stored as received. The resurrection block above runs first for
        --                      this reason -- the row it puts back is the row named here.
        --
        -- Rows already 'Succeeded' are excluded. A Succeeded row names a committed version in
        -- HandlerSourceId, and overwriting it from a later failing call in the same run would
        -- make the status lie about data that is present.
        --
        -- Nested TRY, swallowing, for the same reason as the resurrection block: an error
        -- escaping here would replace the error being reported and the caller would be told the
        -- wrong thing entirely. The cost is that a failed flush loses these rows silently, which
        -- is why logs.HandlerLoadStatus.ExecutionLogId carries no foreign key -- see section 7 of
        -- script 310. It is recorded in ContextMessage instead of raised.
        -----------------------------------------------------------------------------------------
        BEGIN TRY
            IF @LoadRunId IS NOT NULL
            BEGIN
                UPDATE s
                   SET Status               = N'Failed'
                     , Outcome              = NULL
                     , CompletedDateUtc     = SYSUTCDATETIME ()
                     , ExecutionLogId       = @ExecutionId
                     , auditModifiedBy      = ORIGINAL_LOGIN ()
                     , auditModifiedDateUtc = SYSUTCDATETIME ()
                  FROM logs.HandlerLoadStatus AS s
                  JOIN @Key AS k
                   ON s.HandlerId  = CAST (k.HandlerId AS NVARCHAR (12))
                  AND s.SourceType = CAST (k.SourceType AS NVARCHAR (1))
                  AND s.Sequence   = k.Sequence
                 WHERE s.LoadRunId = @LoadRunId
                   AND s.IsDeleted = 0
                   AND s.Status   <> N'Succeeded'
                   -- Unlike the success path, the width check may be WHAT THREW, so @Key can
                   -- hold a value wider than the column. Without these two tests the CAST above
                   -- would truncate it into some OTHER handler's key and mark that handler
                   -- failed -- the one mistake in this procedure that corrupts rather than
                   -- loses. An over-wide key simply matches nothing, which is correct: it never
                   -- named a real handler.
                   AND LEN (k.HandlerId) <= 12
                   AND LEN (k.SourceType) <= 1;

                SET @FailedStatusRows = @@ROWCOUNT;

                -- '+' rather than CONCAT on the left, on purpose: '+' propagates NULL, so a
                -- failure that happened before @ContextMessage was set yields no stray comma.
                SET @ContextMessage = CONCAT (COALESCE (@ContextMessage + N', ', N'')
                                            , N'statusFailed=', @FailedStatusRows);
            -- No semicolon: a terminated IF cannot take an ELSE.
            END
            ELSE
            BEGIN
                SET @ContextMessage = CONCAT (COALESCE (@ContextMessage + N', ', N'')
                                            , N'statusFailed=n/a (no LoadRunId)');
            END;
        END TRY
        BEGIN CATCH
            -- Swallowed by design; see above. Recorded, though, because a lost flush is the one
            -- way AR5 can under-report a failure without anything saying so.
            SET @ContextMessage = CONCAT (COALESCE (@ContextMessage + N', ', N'')
                                        , N'statusFlushFailed=1');
        END CATCH;

        -- Swallows everything by design, so this call cannot mask the error below it. Runs AFTER
        -- the status flush so that the flush's own result reaches ContextMessage.
        EXEC logs.uspRecordExecutionError
              @ProcedureName   = @ProcName
            , @KeyParameters   = @KeyParameters
            , @ExecutionLogId  = @ExecutionId
            , @ErrorMessage    = @ErrorMsg
            , @ErrorProcedure  = @ErrorProc
            , @ErrorNumber     = @ErrorNumber
            , @ErrorLine       = @ErrorLine
            , @DynamicSql      = @DynamicSql
            , @ContextMessage  = @ContextMessage;

        -- Bare, so the ORIGINAL error number reaches the caller. RAISERROR would make it 50000 and
        -- the client could no longer tell a deadlock from a constraint violation. The leading
        -- semicolon is required: a bare THROW immediately after BEGIN is a syntax error.
        ;THROW;

    END CATCH;

    RETURN 0;
END;
GO

