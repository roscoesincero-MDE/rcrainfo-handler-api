Notes:

IDEMPOTENT, AND THAT IS LOAD-BEARING. Running this twice with the same payload inserts on the first call and changes
nothing on the second: every column is compared with IS DISTINCT FROM and a row that matches is not updated at all.
The AR8 completion UPDATE sits after the COMMIT, so a failure there reports a committed batch as failed and the caller
may retry -- which is only survivable because the retry is a no-op.

SCOPE. The parent table, its RawJson row, and all 18 repeating child collections -- three of which are grandchildren,
nested inside another collection's elements. DA1 deliberately shipped the parent alone first, to settle the set
mechanism and the audit stamping on one statement before the same mapping was replicated nineteen times; the children
were added once the retire rule below had been decided. dbo.HandlerSourceOtherIdentifier is NOT here and never will
be: it comes from a different endpoint and is not keyed to a handler VERSION.

RETIRING A CHILD ROW IS GATED, AND THE GATE IS THE WHOLE DESIGN. A child element has no key of EPA's own, so its only
natural key is (parent surrogate key, OrdinalPosition) -- which means a payload that sends three owners where four are
stored is asserting that the fourth is gone, and WHEN NOT MATCHED BY SOURCE is how that is applied. The hazard is that
a CROSS APPLY OPENJSON cannot distinguish three cases that must not be treated alike: an ABSENT property, an EMPTY
array, and a property EPA has RENAMED all shred to zero rows, with no error and no row-count anomaly. Ungated, the
first EPA release that renames a property would soft-delete every child row of every handler in every batch, silently.

SO THE GATE IS JSON_PATH_EXISTS, ONCE PER COLLECTION PER ELEMENT, RECORDED IN @Collection BEFORE ANY CHILD MERGE RUNS.
It returns 1 for both [] and a populated array and 0 only when the property is absent, which is exactly the
distinction the shred loses. An empty or shorter array is a real removal and retires; an ABSENT property retires
nothing, because absent is not evidence of none. MDE's decision, 2026-09-05. The cost is one JSON_PATH_EXISTS per
collection per element and it is not negotiable down: the alternative is a silent mass delete.

AN ABSENT COLLECTION IS RECORDED, BUT ONLY WHEN IT IS DIAGNOSTIC. logs.DataQualityObservation gets one row per
collection per batch, and only when EPA sent the property for NO element in the batch AND this database holds live
rows for those same parents. That pair is the rename signature. Absent with nothing stored is unremarkable -- most
Maryland handlers have no episodic wastes and never will -- and recording it would put roughly fifteen rows per
handler per night into a table whose entire value is that a row in it means something. The count reaches
logs.ExecutionLog.Comments either way, as absentCollections=N, spelt out even when it is zero.

childRetired IN Comments IS AN ALARM, NOT A STATISTIC. $action reports 'UPDATE' for a revive and a retire alike, so
the retire count is taken from inserted.IsDeleted instead. A retire count that jumps after an EPA release is the
signature of a genuine mass removal; combined with an absentCollections observation it is the signature of a rename.
For that number to be readable it has to return to zero when nothing is happening, which is why WHEN NOT MATCHED BY
SOURCE also tests tgt.IsDeleted = 0 -- an already-retired row is unmatched on every later run too, and without that
test every run would re-stamp auditDeletedDateUtc on rows retired weeks ago.

A CHILD MERGE'S TARGET IS A CTE, AND THAT IS NOT COSMETIC. WHEN NOT MATCHED BY SOURCE over the bare table would make
the engine consider every row of a table that grows without bound; the EXISTS predicate would keep it correct and
would not save the plan. Each MERGE therefore targets a CTE restricted to this batch's parents, which seeks the
child's foreign-key index. A CTE over a single base table with a WHERE clause is insertable, updatable, and accepts
OUTPUT -- all three were measured against this engine before nineteen statements were generated against them.

A GRANDCHILD FINDS ITS PARENT BY JOINING THE TABLE THAT WAS JUST MERGED, NOT BY MERGE ... OUTPUT. OUTPUT cannot serve
as the id map: a matched-but-unchanged row produces no OUTPUT row at all, so on the second run of an unchanged payload
the map would be empty and every grandchild row would be orphaned or retired. Joining the already-merged child on its
unique (ParentId, OrdinalPosition) index always finds it, and costs a seek. This is why CHILD_ORDER must place a
parent before its grandchild, and why generate_schema.py refuses to emit if it does not.

REVIVAL IS DONE HERE, AND SCRIPT 522 IS RIGHT TO INSIST ON IT. Every child and grandchild MERGE matches on (parent,
OrdinalPosition) WITHOUT filtering IsDeleted, exactly as the parent does, so a soft-deleted row whose ordinal EPA is
sending again is REVIVED rather than duplicated. That discharges the obligation dbo.uspSoftDeleteHandlerSourceSet
records in its own header and cannot meet from the other side. The unfiltered match is also what makes a duplicate
impossible: because a deleted row is matched and revived rather than re-inserted, two rows can never come to share one
(parent, ordinal).

G35 IS ANSWERED, AND THE ANSWER IS A TABLE VARIABLE. AR5's logs.HandlerLoadStatus rows are written by a procedure
whose transaction may be doomed, and a rollback would take them with it -- so the failed batch would report nothing
about WHICH handlers it failed, which is the whole reason AR5 exists. MDE's decision was to accumulate the per-handler
set in a table variable, which a rollback does not unwind, and flush it from the CATCH block. No new accumulator was
needed: @Key already holds every element's natural key and is populated before BEGIN TRANSACTION, so the flush also
covers a batch rejected in validation, which never opened a transaction at all. The success half is written INSIDE the
transaction instead, because 'handler X was inserted' is only true if it committed. Rows are UPDATEd, never INSERTed
-- they exist as 'Pending' from the moment the run enumerated its work -- and the failure flush deliberately does not
carry an Outcome, because nothing was applied. logs.HandlerLoadStatus.ExecutionLogId, added additively for this, is
how a Failed row reaches the error text.

WHY THE CHANGE TEST IS COLUMN-BY-COLUMN. IS DISTINCT FROM compares NULLs as equal, which a plain <> does not: with
200-odd nullable columns, a <> test reports 'no change' for every row where any compared value is NULL. The
alternative -- comparing a hash of the payload -- was rejected because it tests the SERIALIZATION rather than the
data. The day EPA reorders a property or changes its whitespace, every row in the batch would be reported as changed
and auditModifiedDateUtc would move across the whole table for a change that did not happen. CLAUDE.md's 'converge, do
not re-apply' rule is precisely this.

THE MATCH IS UNFILTERED, AND MUST BE. The ON clause does not test IsDeleted. UX_dbo_HandlerSource_Natural excludes
soft-deleted rows, so matching on it would report a soft-deleted handler as NOT MATCHED and insert a second row with
the same natural key -- two rows, one live and one deleted, that the filtered unique index cannot reject. Matching
unfiltered and setting IsDeleted = 0 on the matched arm is what keeps the natural key unique across all of history,
and IX_dbo_HandlerSource_Natural_All exists to serve exactly this seek.

HOLDLOCK IS NOT OPTIONAL ON EITHER MERGE. Without it, MERGE takes its read locks and releases them before the write,
so two batches carrying the same handler can both evaluate NOT MATCHED and both insert. The natural-key index would
then reject one of them with a unique-violation on an unattended overnight load. Both joins are seekable, so the range
locks HOLDLOCK takes are on the keys in the batch and not on the table.

WHAT @KeyParameters MAY CONTAIN. Identifiers and counts. @Payload is excluded BY NAME -- logging it would copy
thousands of regulated-entity records into logs.ExecutionLog, which has a different read audience and a different
retention policy from the tables the payload lands in. The same restriction applies to @Comments, @ContextMessage and
@DynamicSql. From MDE's own template: do NOT include parameters such as passwords and Personally Identifiable
Information.

VALIDATION IS BEFORE BEGIN TRANSACTION. All four checks -- valid JSON, a complete natural key, a key that fits its
column, and no duplicate key within the batch -- run inside the TRY block and before the transaction opens, so a
rejected payload is recorded as a failed execution like any other with no transaction to unwind. The duplicate check
in particular replaces error 8672 raised from inside the MERGE with a message that names the offending key.

A RENAMED OR MIS-CASED PROPERTY SHREDS TO NULL SILENTLY. OPENJSON matches property names case-sensitively regardless
of database collation, and a path that matches nothing is not an error. Generating this mapping and the CREATE TABLE
from the same spec removes the drift between them; it does not remove the drift between this mapping and EPA. G28's
round-trip tests are what compensate, and the four natural-key columns are checked for NULL above because those are
the ones whose silence would corrupt rather than merely lose.

@ProcName FALLS BACK TO A LITERAL, AND THE LITERAL IS THE ONE THE LOADER ACTUALLY USES. OBJECT_NAME (@@PROCID) and
OBJECT_SCHEMA_NAME (@@PROCID) return NULL for a principal denied metadata visibility, and script 050 denies exactly
that to both application logins. Measured: RCRAInfoMonitor holds EXECUTE = 1 on a procedure and still reads NULL from
OBJECT_ID on it, because permission to run an object is not permission to see its name. So the COALESCE is not a
defensive nicety for ad-hoc batches -- it is the branch every single loader call takes, and with a placeholder there
every row the console app wrote would carry no procedure name, which is the one column the monitoring web app groups
by. The literal is emitted from the same constant as the CREATE OR ALTER PROCEDURE name, so a rename moves both. The
dynamic half is kept because it still resolves for the developer.

THE COMPLETION UPDATE IS AFTER THE COMMIT, AND THAT HAS A CONSEQUENCE. If the COMMIT succeeds and the completion
UPDATE then fails, control reaches the CATCH block with XACT_STATE () = 0, the error is recorded against the existing
row, and a committed batch is reported as failed. Survivable only because of the first note.

